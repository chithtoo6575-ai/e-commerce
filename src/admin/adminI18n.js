export function getAdminLanguage() {
  try {
    return window.localStorage.getItem(ADMIN_LANGUAGE_KEY) === 'my' ? 'my' : 'en'
  } catch {
    return 'en'
  }
}

export function setAdminLanguage(language) {
  const value = language === 'my' ? 'my' : 'en'
  try {
    window.localStorage.setItem(ADMIN_LANGUAGE_KEY, value)
  } catch {
    // The in-memory application state remains usable when browser storage is unavailable.
  }
  return value
}

export function adminT(value, language = getAdminLanguage()) {
  if (typeof value !== 'string' || language !== 'my') return value
  if (MYANMAR[value]) return MYANMAR[value]

  let match = value.match(/^Banner (.*?) is now (Active|Inactive)$/)
  if (match) return `ဘန်နာ ${match[1]} ကို ${adminT(match[2], language)} အဖြစ် သတ်မှတ်လိုက်ပါပြီ။`
  match = value.match(/^Category "(.+)" is now (Enabled|Disabled)$/)
  if (match) return `“${match[1]}” အမျိုးအစားကို ${adminT(match[2], language)} လုပ်လိုက်ပါပြီ။`
  match = value.match(/^Customer account (.+) marked (Active|Inactive|Suspended)$/)
  if (match) return `ဖောက်သည်အကောင့် ${match[1]} ကို ${adminT(match[2], language)} ဟု သတ်မှတ်လိုက်ပါပြီ။`
  match = value.match(/^Delivery partner "(.+)" is now (Active|Inactive)$/)
  if (match) return `“${match[1]}” ပို့ဆောင်ရေးပါတနာကို ${adminT(match[2], language)} လုပ်လိုက်ပါပြီ။`
  match = value.match(/^Section "(.+)" is now (Enabled|Disabled)$/)
  if (match) return `“${match[1]}” အပိုင်းကို ${adminT(match[2], language)} လုပ်လိုက်ပါပြီ။`
  match = value.match(/^Block "(.+)" is now (Visible|Hidden)$/)
  if (match) return `“${match[1]}” အပိုင်းကို ${adminT(match[2], language)} လုပ်လိုက်ပါပြီ။`
  match = value.match(/^Payment method "(.+)" is now (Active|Inactive)$/)
  if (match) return `“${match[1]}” ငွေပေးချေနည်းလမ်းကို ${adminT(match[2], language)} လုပ်လိုက်ပါပြီ။`
  match = value.match(/^Support channel "(.+)" is now (Active|Inactive)$/)
  if (match) return `“${match[1]}” အကူအညီဆက်သွယ်ရေးလမ်းကြောင်းကို ${adminT(match[2], language)} လုပ်လိုက်ပါပြီ။`
  match = value.match(/^Order status updated to (.+)$/)
  if (match) return `အော်ဒါအခြေအနေကို ${adminT(match[1], language)} သို့ အပ်ဒိတ်လုပ်ပြီးပါပြီ။`
  match = value.match(/^Payment marked as (.+)$/)
  if (match) return `ငွေပေးချေမှုကို ${adminT(match[1], language)} ဟု သတ်မှတ်လိုက်ပါပြီ။`
  match = value.match(/^Shipping zone "(.+)" is now (Active|Inactive)$/)
  if (match) return `“${match[1]}” ပို့ဆောင်ရေးဇုန်ကို ${adminT(match[2], language)} လုပ်လိုက်ပါပြီ။`
  match = value.match(/^Sub category "(.+)" is now (Active|Inactive)$/)
  if (match) return `“${match[1]}” အမျိုးအစားခွဲကို ${adminT(match[2], language)} လုပ်လိုက်ပါပြီ။`
  match = value.match(/^Help item marked (Active|Inactive)$/)
  if (match) return `အကူအညီမေးခွန်းကို ${adminT(match[1], language)} လုပ်လိုက်ပါပြီ။`
  match = value.match(/^Broadcast notification "(.+)" sent to (.+)!$/)
  if (match) return `“${match[1]}” ကြေညာချက်ကို ${match[2]} သို့ ပို့ပြီးပါပြီ။`
  match = value.match(/^Recorded (Stock In|Stock Out|Adjustment|Return|Damaged) for (.+)$/)
  if (match) return `${adminT(match[1], language)} ကို မှတ်တမ်းတင်ပြီးပါပြီ: ${match[2]}`
  match = value.match(/^Orders above (.+)$/)
  if (match) return `${match[1]} အထက်ရှိ အော်ဒါများ`
  match = value.match(/^Confirm Bulk (.+)$/)
  if (match) return `${adminT('Confirm Action', language)}: ${match[1]}`
  match = value.match(/^Are you sure you want to apply this action to (\d+) product\(s\)\?$/)
  if (match) return `ဤလုပ်ဆောင်ချက်ကို ကုန်ပစ္စည်း ${match[1]} ခုတွင် အသုံးပြုရန် သေချာပါသလား။`
  match = value.match(/^\+(.+) \/ kg$/)
  if (match) return `တစ်ကီလိုလျှင် +${match[1]}`
  match = value.match(/^Banner updated$/)
  if (match) return 'ဘန်နာကို အပ်ဒိတ်လုပ်ပြီးပါပြီ။'
  match = value.match(/^Are you sure you want to change order (.+) to "(.+)"\?$/)
  if (match) return `အော်ဒါ ${match[1]} ၏ အခြေအနေကို “${adminT(match[2], language)}” သို့ ပြောင်းရန် သေချာပါသလား။`
  return value
}

export function AdminLanguageSelector({ language, onChange, className = '' }) {
  return React.createElement(
    'select',
    {
      className: `admin-language-selector ${className}`.trim(),
      value: language,
      'aria-label': adminT('Admin language'),
      onChange: (event) => onChange?.(event.target.value)
    },
    React.createElement('option', { value: 'my' }, ADMIN_LANGUAGES.my),
    React.createElement('option', { value: 'en' }, ADMIN_LANGUAGES.en)
  )
}
